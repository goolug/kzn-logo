// Naive single-file bundler — good enough because the sources follow two
// rules: no import aliasing, and unique top-level names across modules.
// Emits:
//   dist/kzn-logo.standalone.js   the library as one classic module script
//   dist/demo-standalone.html     the full demo as one self-contained file
import { readFile, writeFile, mkdir } from 'node:fs/promises';

const read = (p) => readFile(new URL(`../${p}`, import.meta.url), 'utf8');

function strip(src) {
  return src
    .replace(/^import[^;]*;\s*$/gm, '')
    .replace(/^export\s+(?=(const|let|var|function|class)\b)/gm, '')
    .replace(/^export\s*\{[^}]*\}\s*(from[^;]*)?;\s*$/gm, '')
    .replace(/^export\s+\*\s+from[^;]*;\s*$/gm, '')
    .trim();
}

const order = ['src/core.js', 'src/motion.js', 'src/svg.js', 'src/webgl.js', 'src/element.js'];
const parts = [];
for (const p of order) parts.push(`// ---- ${p} ----\n${strip(await read(p))}`);
const lib = parts.join('\n\n');

await mkdir(new URL('../dist', import.meta.url), { recursive: true });
await writeFile(
  new URL('../dist/kzn-logo.standalone.js', import.meta.url),
  `// kzn-logo — single-file build (generated by tools/build-standalone.mjs)\n${lib}\n`
);

const demo = strip(await read('demo.js'));
const html = (await read('index.html')).replace(
  /<script type="module" src="\.\/demo\.js"><\/script>/,
  () => `<script type="module">\n${lib}\n\n// ---- demo.js ----\n${demo}\n</script>`
);
await writeFile(new URL('../dist/demo-standalone.html', import.meta.url), html);

const env = strip(await read('env.js'));
const envHtml = (await read('env.html')).replace(
  /<script type="module" src="\.\/env\.js"><\/script>/,
  () => `<script type="module">\n${lib}\n\n// ---- env.js ----\n${env}\n</script>`
);
await writeFile(new URL('../dist/env-standalone.html', import.meta.url), envHtml);

console.log('dist: kzn-logo.standalone.js, demo-standalone.html, env-standalone.html');
